let currentLang = typeof localStorage !== 'undefined' ? (localStorage.getItem('gac_srtool_lang') || 'th') : 'th';

export function getCurrentLanguage() {
  return currentLang;
}

export function setLanguage(langCode) {
  if (TRANSLATIONS[langCode]) {
    currentLang = langCode;
    if (typeof localStorage !== 'undefined') {
      localStorage.setItem('gac_srtool_lang', langCode);
    }
  }
}

export function t(key, vars = {}) {
  const dict = TRANSLATIONS[currentLang] || TRANSLATIONS.en || TRANSLATIONS.th;
  let text = dict[key] || TRANSLATIONS.en[key] || TRANSLATIONS.th[key] || key;

  // Substitute variables e.g. {id}, {rank}, {name}
  for (const [vKey, vVal] of Object.entries(vars)) {
    text = text.replace(new RegExp(`\\{${vKey}\\}`, 'g'), vVal);
  }
  return text;
}

export function translateElement(elem) {
  const dict = TRANSLATIONS[currentLang] || TRANSLATIONS.en;
  return dict.elements?.[elem] || TRANSLATIONS.en.elements?.[elem] || elem;
}

export function translatePath(path) {
  const dict = TRANSLATIONS[currentLang] || TRANSLATIONS.en;
  return dict.paths?.[path] || TRANSLATIONS.en.paths?.[path] || path;
}
